import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const artifactPath = path.resolve(__dirname, "../../contracts/out/Gastem.sol/Gastem.json");
const targetPath = path.resolve(__dirname, "../src/abi.ts");

if (!fs.existsSync(artifactPath)) {
  console.error(`Artifact not found at ${artifactPath}. Please run "forge build" in contracts/ first.`);
  process.exit(1);
}

try {
  const artifactRaw = fs.readFileSync(artifactPath, "utf-8");
  const artifact = JSON.parse(artifactRaw);

  if (!artifact.abi) {
    console.error("ABI not found in artifact JSON.");
    process.exit(1);
  }

  const fileContent = `// Auto-generated by scripts/sync-abi.mjs - DO NOT EDIT MANUALLY\nexport const gastemAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;

  fs.writeFileSync(targetPath, fileContent, "utf-8");
  console.log(`Successfully synced ABI to ${targetPath}`);
} catch (error) {
  console.error("Failed to sync ABI:", error);
  process.exit(1);
}
